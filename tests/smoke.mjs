    await expect(page.locator('.place-row')).toHaveCount(65);
    await expect(page.locator('#map img.leaflet-marker-icon')).toHaveCount(34);
    await expect.poll(async () => page.locator('#map img.leaflet-marker-icon').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0 && image.getBoundingClientRect().width > 20))).toBeTruthy();
    expect(await page.locator('#map img.leaflet-marker-icon').evaluateAll(images => images.every(image => image.getAttribute('src')?.startsWith('/icons/polling/ballot-')))).toBeTruthy();
    expect(await page.locator('#map path.leaflet-interactive').evaluateAll(paths => new Set(paths.map(path => path.getAttribute('fill'))).size)).toBe(5);
    await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].length > 0 && [...document.querySelectorAll('.leaflet-tile')].every(image => image.complete), { timeout: 15000 }).catch(() => {});
    await page.locator('.map-workspace').screenshot({ path: `${out}/voting-${name}.png` });
    await page.getByRole('searchbox', { name: 'Search places, precincts or addresses' }).fill('2003 Riverside');
    await expect(page.locator('.place-row')).toHaveCount(1);
    await page.getByRole('button', { name: 'Show Professional Learning Center (VV1) on map', exact: true }).click();
