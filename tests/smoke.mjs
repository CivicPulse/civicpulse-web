    await page.getByRole('searchbox', { name: 'Search places, precincts or addresses' }).fill('');
    await page.getByLabel('Polling places', { exact: false }).uncheck();
    await expect(page.locator('.place-row')).toHaveCount(31);
    await page.locator('#map-choice').selectOption('community');
    await expect(page.locator('#map-status')).toHaveText('3 layers visible · Sample GeoJSON data');
    await expect(page.locator('.place-row')).toHaveCount(8);
    await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].length > 0 && [...document.querySelectorAll('.leaflet-tile')].every(image => image.complete), { timeout: 15000 }).catch(async () => { await page.locator('#basemap').uncheck(); });
    await page.screenshot({ path: `${out}/maps-${name}.png`, fullPage: true });
    await page.getByLabel('Parks', { exact: false }).uncheck();
    await expect(page.locator('.place-row')).toHaveCount(5);
    await page.locator('#map-choice').selectOption('outdoors');
    await expect(page.locator('.place-row')).toHaveCount(6);
    await page.getByRole('searchbox', { name: 'Search places, precincts or addresses' }).fill('Tattnall');
    await expect(page.locator('.place-row')).toHaveCount(1);
    await page.getByRole('button', { name: 'Show Tattnall Square Park on map' }).click();
    await expect(page.locator('.leaflet-popup')).toBeVisible();
    await expect(page.locator('.leaflet-popup')).toContainText('Sample data');
